CREATE TABLE bus_locations (
  id UUID PRIMARY KEY,
  bus_id UUID NOT NULL,
  bus_number VARCHAR(30) NOT NULL,
  latitude NUMERIC(10,7) NOT NULL,
  longitude NUMERIC(10,7) NOT NULL,
  speed NUMERIC(6,2), heading NUMERIC(5,2), recorded_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_bus_locations_latest ON bus_locations(bus_id, recorded_at DESC);
